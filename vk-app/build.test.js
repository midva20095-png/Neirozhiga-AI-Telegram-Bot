const assert = require('assert');
const fs = require('fs');
const path = require('path');
const { test } = require('node:test');

test('приложение ВК остаётся на своём адресе и сразу сообщает о запуске', () => {
    require('./build.js');
    const html = fs.readFileSync(path.join(__dirname, 'build/index.html'), 'utf8');
    assert.equal(html.includes('location.replace'), false);
    assert.equal(html.includes('telegram.org'), false);
    assert.equal(html.includes('VKWebAppInit'), true);
    assert.equal(html.includes('@vkontakte/vk-bridge'), true);
    assert.equal(html.includes('document.write'), false);
    assert.equal(html.includes('if (echoing) return;'), true);
    assert.equal(html.includes('window.__nyVkBoot'), true);
    assert.equal(html.split('VKWebAppInit').length, 3);
    const source = fs.readFileSync(path.join(__dirname, '../public/index.html'), 'utf8');
    assert.equal(source.includes('@vkontakte/vk-bridge'), false);
    assert.equal(html.includes('VKWebAppGetAuthToken'), true);
    assert.equal(html.includes('function launchFields'), true);
    assert.equal(html.includes('54901511'), true);
    assert.equal(html.includes('54895627'), false);
    assert.equal(html.includes("method: 'POST'"), true);
    assert.equal(html.includes("'/api/vk/session'"), true);
    assert.equal(html.includes('window.__nyApi'), true);
    assert.equal(html.includes('https://neirozhiga-ai-telegram-bot-production-7ae5.up.railway.app'), true);
    assert.equal(html.includes('nySave'), true);
    assert.equal(fs.existsSync(path.join(__dirname, 'build/widget/chat.jpg')), true);
    assert.equal(fs.existsSync(path.join(__dirname, 'build/cover.jpg')), true);
    assert.equal(html.includes("['tpl', 'Шаблоны']"), false);
    assert.equal(html.includes("['models', 'Модели']"), false);
    assert.equal(html.includes('class="cover"'), true);
    assert.equal(html.includes('src="cover.jpg"'), true);
    assert.equal(html.includes('function tplOf'), true);
    assert.equal(html.includes("type: 'ny-tpl'"), true);
    assert.equal(source.includes('function openSharedTpl'), true);
    assert.equal(source.includes('function hashTpl'), true);
    const door = fs.readFileSync(path.join(__dirname, '../public/vk.html'), 'utf8');
    assert.equal(door.includes("key === 'tpl'"), true);
    assert.equal(door.includes("dest.set('tpl', fromHash[1])"), true);
    const initAt = html.indexOf('VKWebAppInit');
    const appAt = html.indexOf('function downloadWork');
    assert.ok(initAt > 0 && appAt > initAt);
    const parts = [...html.matchAll(/<script>([\s\S]*?)<\/script>/g)].map(item => item[1]);
    assert.ok(parts.length >= 3);
    parts.forEach(part => { new Function(part); });
});
