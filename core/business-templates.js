async function ensure(db) {
    const saved = await db.getSettings(['business_templates_v1']);
    if (saved && saved.business_templates_v1) return { skipped: true, added: 0 };
    const existing = await db.listTemplates(true);
    const titles = new Set((existing || []).map(row => String(row.title || '').trim().toLowerCase()));
    let added = 0;
    for (const row of list()) {
        if (titles.has(String(row.title).trim().toLowerCase())) continue;
        await db.saveTemplate(row);
        added += 1;
    }
    await db.setSetting('business_templates_v1', { added });
    return { skipped: false, added };
}

