function item(topic, build, extra, spec) {
    return Object.assign({
        title: spec.title,
        description: spec.desc,
        category: extra.category || 'image',
        prompt: build(spec),
        model: extra.model,
        quality: extra.quality || '',
        cost: extra.cost,
        formats: extra.formats || '',
        topics: topic,
        fields: extra.fields,
        audience: 'all',
        active: true,
        sort: -10
    }, spec.row || {});
}

